export type T = (key: Key, vars?: Record<string, string | number>) => string

export function translator(lang: Lang): T {
  const table: Record<Key, string> = lang === 'en' ? en : zh
  return (key, vars) => {
    let s = table[key] ?? key
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }
}

export const hasKey = (key: string): key is Key => key in zh

export const toLang = (s?: string | null): Lang => ((s ?? '').toLowerCase().startsWith('en') ? 'en' : 'zh')

const STORE = 'rlyeh.studio.lang'

export function savedLang(): Lang | null {
  try {
    const v = localStorage.getItem(STORE)
    return v === 'zh' || v === 'en' ? v : null
  } catch {
    return null
  }
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem(STORE, lang)
  } catch {
    /* 隐私模式之类：不记也行 */
  }
}

export const LangContext = createContext<{ lang: Lang; t: T; setLang: (l: Lang) => void }>({
  lang: 'zh',
  t: translator('zh'),
  setLang: () => {},
})

export const useI18n = () => useContext(LangContext)
